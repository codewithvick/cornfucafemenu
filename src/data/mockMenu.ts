function mapOnlineToMenuItem(p: any): MenuItem {
  const rawCat = (p.categoryId || '').toLowerCase();
  let category: any = 'food';
  if (rawCat === 'boba-tea' || rawCat === 'boba') category = 'boba';
  else if (rawCat === 'juices' || rawCat === 'juice') category = 'juice';
  else if (rawCat === 'matcha') category = 'matcha';
  else if (rawCat === 'smoothies' || rawCat === 'smoothie') category = 'smoothies';
  else if (rawCat === 'espresso') category = 'espresso';
  else if (rawCat === 'food') category = 'food';

  return {
    id: p.id,
    name: p.name,
    category,
    price: Number(p.price) || 0,
    price700ml: p.secondaryPrice ? Number(p.secondaryPrice) : undefined,
    available: 35,
    sold: 15,
    image: p.image || '',
    description: p.description || p.tagline || '',
    tags: p.badge ? [p.badge] : (p.sizeLabel ? [p.sizeLabel] : []),
    isAvailable: p.inStock !== false,
  };
}

export const INITIAL_MENU_ITEMS: MenuItem[] = RAW_ONLINE_PRODUCTS.map(mapOnlineToMenuItem);
